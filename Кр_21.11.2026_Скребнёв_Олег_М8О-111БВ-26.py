n = abs(int(input()))

sp = []

sp.append(n)
sp.append(1)

if n == 0: print(f"{0} - у нуля нет делителей")

else:
    for x in range(2, int(n ** 0.5) + 1):
        if n % x == 0:
            sp.append(x)
            sp.append(n // x)

print(sorted(sp))

