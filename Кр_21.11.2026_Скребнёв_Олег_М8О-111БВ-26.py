"""НОМЕР 3"""
import math

chisl = int(input())
znam = int(input())

if znam == 0:
    print("НА 0 ДЕЛИТЬ НЕЛЬЗЯЯЯЯ!!!!")
elif chisl == 0:
    print(f"числитель = {chisl}, знаменатель = {znam}, т.к. числитель = 0, то дробь = 0, сократить нельзя")
else:
    nod = math.gcd(chisl, znam) ###nod - наибольший общий делитель
    chisl //= nod
    znam //= nod

    if znam < 0:
        chisl = -chisl
        znam = -znam

    if znam == 1:
        print(f"{chisl} - дробь сокращается до одного числа")
    else:
        print(f"{chisl} - числитель, {znam} - знаменатель")

